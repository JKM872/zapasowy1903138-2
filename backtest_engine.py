def _print_comparison(res: Dict[str, Dict]) -> None:
    on = res.get('with_poisson')
    off = res.get('without_poisson')
    if on and off:
        print(f"\n{'='*64}")
        print(f"  SIMULATION ABLATION — Poisson draw model  (n={on['n']})")
        print(f"{'='*64}")
        print(f"  {'metric':<14}{'without':>12}{'with':>12}{'delta':>12}")
        print(f"  {'-'*50}")
        for key, better_lower in (
            ('accuracy', False), ('brier', True),
            ('log_loss', True), ('draw_brier', True),
        ):
            o = off[key]
            n = on[key]
            delta = n - o
            arrow = ''
            if better_lower:
                arrow = '  better' if delta < 0 else ('  worse' if delta > 0 else '')
            else:
                arrow = '  better' if delta > 0 else ('  worse' if delta < 0 else '')
            print(f"  {key:<14}{o:>12.4f}{n:>12.4f}{delta:>+12.4f}{arrow}")
        print(f"\n  draws in sample: {on['draw_n']} / {on['n']} "
              f"({100*on['draw_n']/max(1,on['n']):.1f}%)")
        print(f"{'='*64}\n")
    else:
        for label, m in res.items():
            if label == 'reliability' and isinstance(m, list):
                print(f"\n[reliability]  (predicted vs observed hit-rate)")
                print(f"   {'range':<12}{'n':>6}{'predicted':>12}{'observed':>12}")
                for b in m:
                    print(f"   {b['range']:<12}{b['n']:>6}"
                          f"{b['avg_predicted']:>12.3f}{b['observed']:>12.3f}")
                continue
            if not isinstance(m, dict):
                continue
            print(f"\n[{label}]")
            for k, v in m.items():
                print(f"   {k:<14}: {v}")


def main() -> None:
    ap = argparse.ArgumentParser(description='Backtest the football scoring engine')
    ap.add_argument('--simulate', type=int, metavar='N',
                    help='Run Monte-Carlo ablation with N simulated matches')
    ap.add_argument('--seed', type=int, default=42, help='RNG seed for simulation')
    ap.add_argument('--odds-noise', type=float, default=0.1,
                    help='Market noise level (0=sharp, 0.3=loose) for simulation')
    ap.add_argument('--odds-missing', type=float, default=0.0,
                    help='Probability that a match has no odds at all (0..1)')
    ap.add_argument('--real', metavar='PATH',
                    help='Backtest on a JSON/CSV file containing actual_result')
    ap.add_argument('--json', action='store_true', help='Emit raw JSON only')
    args = ap.parse_args()

    if args.simulate:
        res = run_simulation(args.simulate, seed=args.seed,
                             odds_noise=args.odds_noise,
                             odds_missing_prob=args.odds_missing)
    elif args.real:
        res = run_real(args.real)
    else:
        ap.print_help()
        return

    if args.json:
        print(json.dumps(res, indent=2))
    else:
        _print_comparison(res)


if __name__ == '__main__':
    main()
