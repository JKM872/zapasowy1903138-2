def _load_rows(path: str) -> List[Dict]:
    if path.endswith('.csv'):
        import csv
        with open(path, 'r', encoding='utf-8-sig') as fh:
            return list(csv.DictReader(fh))
    with open(path, 'r', encoding='utf-8-sig') as fh:
        data = json.load(fh)
    if isinstance(data, list):
        return data
    if isinstance(data, dict):
        for key in ('matches', 'results', 'predictions', 'data'):
            if key in data and isinstance(data[key], list):
                return data[key]
    return []


def run_real(path: str) -> Dict[str, Dict]:
    """Backtest on rows carrying ``actual_result`` ('1'/'X'/'2')."""
    rows = _load_rows(path)
    eng = FootballScoringEngine()
    metrics = BacktestMetrics(f'real:{os.path.basename(path)}')

    # Reliability bins: does predicted probability match observed frequency?
    bins = [(0.0, 0.3), (0.3, 0.45), (0.45, 0.6), (0.6, 0.75), (0.75, 1.01)]
    bin_pred: List[float] = [0.0] * len(bins)
    bin_hit: List[float] = [0.0] * len(bins)
    bin_cnt: List[int] = [0] * len(bins)

    used = 0
    for row in rows:
        actual = str(row.get('actual_result', '')).strip().upper()
        if actual not in ('1', 'X', '2'):
            continue
        sm = eng.score_match(row)
        metrics.add(
            _probs_from_scored(sm), actual, sm.best_pick,
            ev=sm.ev, odds=sm.best_odds,
        )
        # Reliability: bucket the model's confidence in its own pick.
        p_pick = sm.best_prob
        for bi, (lo, hi) in enumerate(bins):
            if lo <= p_pick < hi:
                bin_pred[bi] += p_pick
                bin_hit[bi] += 1.0 if sm.best_pick == actual else 0.0
                bin_cnt[bi] += 1
                break
        used += 1

    if used == 0:
        print(f"[backtest] No rows with actual_result in {path}")

    reliability = []
    for bi, (lo, hi) in enumerate(bins):
        if bin_cnt[bi] > 0:
            reliability.append({
                'range': f'{lo:.2f}-{hi:.2f}',
                'n': bin_cnt[bi],
                'avg_predicted': round(bin_pred[bi] / bin_cnt[bi], 3),
                'observed': round(bin_hit[bi] / bin_cnt[bi], 3),
            })

    out = {'real': metrics.summary()}
    if reliability:
        out['reliability'] = reliability  # type: ignore[assignment]
    return out


